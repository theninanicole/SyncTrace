-- Validation metrics (M1–M8). See docs/validation-metrics.md.
--
-- Written defensively: existing deployments already have the legacy tables (created by
-- Hibernate ddl-auto=update), while a fresh database runs Flyway before Hibernate creates
-- anything. Every statement therefore works in both cases.

-- ── M1, M2, M3, M6, M8: one row per measured operation ──────────────────────
CREATE TABLE IF NOT EXISTS validation_events (
    id               BIGSERIAL PRIMARY KEY,
    team_id          VARCHAR(120),
    user_id          VARCHAR(64),
    metric_code      VARCHAR(4)   NOT NULL CHECK (metric_code IN ('M1', 'M2', 'M3', 'M6', 'M8')),
    operation        VARCHAR(40)  NOT NULL,
    repository_id    BIGINT,
    export_format    VARCHAR(8),
    analysis_run_id  VARCHAR(64),
    started_at       TIMESTAMPTZ  NOT NULL,
    ended_at         TIMESTAMPTZ  NOT NULL,
    duration_ms      BIGINT       NOT NULL,
    status           VARCHAR(10)  NOT NULL CHECK (status IN ('success', 'failed', 'timeout')),
    error_message    TEXT,
    item_count       INTEGER,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_validation_events_team_metric_time
    ON validation_events (lower(team_id), metric_code, started_at);
CREATE INDEX IF NOT EXISTS ix_validation_events_run ON validation_events (analysis_run_id);

-- ── M4: mapping stage sessions (reopening inserts a new row) ────────────────
CREATE TABLE IF NOT EXISTS validation_stage_sessions (
    id                            BIGSERIAL PRIMARY KEY,
    team_id                       VARCHAR(120) NOT NULL,
    stage                         VARCHAR(20)  NOT NULL CHECK (stage IN
                                      ('proposal_srs', 'srs_sdd', 'srs_std', 'srs_spmp', 'sdd_impl')),
    started_at                    TIMESTAMPTZ  NOT NULL,
    finalized_at                  TIMESTAMPTZ,
    wall_clock_ms                 BIGINT,
    active_ms                     BIGINT       NOT NULL DEFAULT 0,
    last_heartbeat_at             TIMESTAMPTZ,
    finalized_by                  VARCHAR(64),
    links_saved                   INTEGER,
    unmapped_sources_at_finalize  INTEGER,
    created_at                    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_validation_stage_session_open
    ON validation_stage_sessions (lower(team_id), stage) WHERE finalized_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_validation_stage_sessions_team_time
    ON validation_stage_sessions (lower(team_id), started_at);

-- ── M5: reuse mapping_suggestions; keep every suggestion ever generated ─────
-- Same shape Hibernate generates for MappingSuggestion, so ddl-auto=update accepts it.
CREATE TABLE IF NOT EXISTS mapping_suggestions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_code            VARCHAR(255) NOT NULL,
    stage                VARCHAR(40)  NOT NULL,
    source_id            BIGINT       NOT NULL,
    target_component_id  BIGINT       NOT NULL,
    score                FLOAT(53)    NOT NULL,
    reason               VARCHAR(500),
    status               VARCHAR(20)  NOT NULL,
    run_id               VARCHAR(255),
    decided_by           VARCHAR(255),
    decided_at           TIMESTAMP(6),
    created_at           TIMESTAMP(6)
);
ALTER TABLE mapping_suggestions
    ADD COLUMN IF NOT EXISTS resulting_link_id     BIGINT,
    ADD COLUMN IF NOT EXISTS resulting_link_count  INTEGER,
    ADD COLUMN IF NOT EXISTS decided_by_user_id    VARCHAR(64),
    ADD COLUMN IF NOT EXISTS decision_method       VARCHAR(12),
    ADD COLUMN IF NOT EXISTS withdrawn_at          TIMESTAMP(6),
    ADD COLUMN IF NOT EXISTS withdrawn_reason      VARCHAR(12),
    ADD COLUMN IF NOT EXISTS system_rejected       BOOLEAN NOT NULL DEFAULT FALSE;

-- The M5 record under the names used in the validation plan.
CREATE OR REPLACE VIEW ai_link_suggestions AS
SELECT id,
       team_code                AS team_id,
       lower(stage)             AS stage,
       source_id,
       target_component_id      AS target_id,
       reason,
       score,
       run_id,
       created_at               AS generated_at,
       lower(status)            AS decision,
       decided_at,
       decided_by_user_id       AS decided_by,
       decision_method,
       resulting_link_id,
       resulting_link_count,
       withdrawn_at,
       withdrawn_reason,
       system_rejected
FROM mapping_suggestions;

-- ── M7: coverage of one analysis run ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS validation_analysis_coverage (
    id                        BIGSERIAL PRIMARY KEY,
    analysis_run_id           VARCHAR(64)  NOT NULL,
    team_id                   VARCHAR(120) NOT NULL,
    gaps_detected             INTEGER      NOT NULL,
    gaps_provisional          INTEGER      NOT NULL DEFAULT 0,
    gaps_with_explanation     INTEGER      NOT NULL,
    gaps_with_recommendation  INTEGER      NOT NULL,
    gaps_with_both            INTEGER      NOT NULL,
    generation_failures       INTEGER      NOT NULL,
    recommendation_status     VARCHAR(10)  NOT NULL CHECK (recommendation_status IN ('success', 'failed', 'timeout')),
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_validation_coverage_team_time
    ON validation_analysis_coverage (lower(team_id), created_at);

-- ── Optional named windows a teacher can filter exports by ──────────────────
CREATE TABLE IF NOT EXISTS validation_sessions (
    id            BIGSERIAL PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    session_date  DATE         NOT NULL,
    starts_at     TIMESTAMPTZ  NOT NULL,
    ends_at       TIMESTAMPTZ  NOT NULL,
    team_ids      TEXT         NOT NULL DEFAULT '',
    created_by    VARCHAR(64),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_validation_sessions_window CHECK (ends_at > starts_at)
);

-- ── Per-team summary, refreshed after each recorded event (all-time window) ─
CREATE TABLE IF NOT EXISTS validation_team_summary (
    team_id            VARCHAR(120) NOT NULL,
    metric_code        VARCHAR(4)   NOT NULL,
    stage              VARCHAR(20)  NOT NULL DEFAULT '',
    count              INTEGER      NOT NULL,
    median_ms          BIGINT,
    max_ms             BIGINT,
    min_ms             BIGINT,
    pct_within_target  NUMERIC(5, 1),
    target_met         BOOLEAN,
    accepted           INTEGER,
    edited             INTEGER,
    rejected           INTEGER,
    pending            INTEGER,
    acceptance_rate    NUMERIC(5, 1),
    coverage_pct       NUMERIC(5, 1),
    last_updated       TIMESTAMPTZ  NOT NULL,
    PRIMARY KEY (team_id, metric_code, stage)
);
